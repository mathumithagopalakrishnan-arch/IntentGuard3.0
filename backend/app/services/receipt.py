"""Intent Integrity Receipt: one self-contained JSON record of a transaction, with a hash over its own body."""
import json
from ..core.fingerprint import sha256_hex
from . import service as s
from .chain import build_chain
from .payments import get_payment_row, payment_view


def build_receipt(conn, tid):
    t = s.get_transaction(conn, tid)
    ir = s._row(conn, "intents", t["intent_id"], "intent")
    orow = s._row(conn, "offers", t["offer_id"], "offer")
    offer = json.loads(orow["offer_json"])
    pay = payment_view(get_payment_row(conn, tid))
    if pay:
        pay.pop("approve_url", None)
    body = {
        "receipt_type": "IntentGuard Intent Integrity Receipt", "version": 1,
        "environment": "PayPal SANDBOX (test money). Merchant data is SYNTHETIC unless stated otherwise.",
        "transaction_id": tid,
        "original_intent": {"instruction": ir["instruction"], "passport": json.loads(ir["constraints_json"]), "fingerprint_sha256": ir["fingerprint"],
                            "interpreted_by": ir["source"], "confirmed_at": ir["confirmed_at"]},
        "merchant_offer": {"offer": offer, "synthetic": bool(orow["synthetic"]), "threat_findings": t["verification"]["threats"]},
        "cart": t["cart"],
        "verification": {"decision": t["verification"]["decision"], "server_total_minor_units": t["verification"]["server_total"],
                         "transaction_fingerprint_sha256": t["verification"]["transaction_fingerprint"], "checks": t["verification"]["checks"]},
        "intent_drift": t["drift"],
        "consent": t["consent"], "consent_state": t["consent_state"],
        "paypal_sandbox_payment": pay,
        "integrity_chain": build_chain(conn, tid),
        "audit_events": list(reversed(s.list_audit(conn, tid, 500))),
        "audit_log_check": s.verify_audit_chain(conn),
        "limits": ["A matching hash proves data was not changed. It does not prove a merchant is honest.",
                   "This receipt is generated by an independent hackathon prototype. It is not endorsed by PayPal and is not legal or financial proof."],
    }
    return {"receipt": body, "receipt_sha256": sha256_hex(body)}
